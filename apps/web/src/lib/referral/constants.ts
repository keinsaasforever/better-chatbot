/**
 * Shared referral constants.
 *
 * Imported from the middleware (edge runtime), from server routes and from
 * client components alike, so this module must stay free of `server-only`,
 * node built-ins and secret env vars. The Autumn program id lives in
 * `service.ts` instead — it is server-side configuration and would be
 * `undefined` in a browser bundle anyway.
 */

/** Query parameter carrying a referral code on a landing URL. */
export const REFERRAL_QUERY_PARAM = "ref";

/**
 * Cookie that carries a captured referral code from the landing page through
 * sign-up. `httpOnly`, so only the redeem route reads it back.
 */
export const REFERRAL_COOKIE = "referral_ref";

/**
 * Codes are generated by Autumn, so this is a sanity filter rather than a
 * security boundary: it keeps junk out of the cookie before it is ever sent
 * onward. Autumn itself decides whether a code is valid.
 */
export const REFERRAL_CODE_PATTERN = /^[A-Za-z0-9_-]{4,64}$/;

/** How long a captured code stays valid before the visitor has to click again. */
export const REFERRAL_COOKIE_MAX_AGE_SECONDS = 30 * 24 * 60 * 60;

/**
 * Credits granted to each side once a referred customer checks out.
 *
 * Display only, and the number this app promises out loud. The grant itself
 * lives in Autumn: a "free product" reward hands over the `referral-bonus`
 * add-on, and that product's `total` item is the authoritative amount. Change
 * one and the other has to follow — a mismatch here is a promise the product
 * does not keep. See docs/referral-program.md.
 */
export const REFERRAL_REWARD_CREDITS = Number(
  process.env.NEXT_PUBLIC_REFERRAL_REWARD_CREDITS ?? 1_000_000,
);

/** Narrow an untrusted query/cookie value down to something worth forwarding. */
export function isValidReferralCode(value: string | undefined | null): boolean {
  return typeof value === "string" && REFERRAL_CODE_PATTERN.test(value);
}
