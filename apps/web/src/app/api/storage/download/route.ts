import { withAuth } from "auth/route-guard";
import { FileNotFoundError } from "lib/errors";
import { serverFileStorage } from "lib/file-storage";
import {
  downloadFilenameFromKey,
  getContentTypeFromFilename,
} from "lib/file-storage/storage-utils";
import logger from "lib/logger";
import { NextResponse } from "next/server";

export const maxDuration = 60;

/** One click, not a shareable link: the redirect target dies quickly. */
const SIGNED_URL_TTL_SECONDS = 60;

/**
 * Content types that may be served with `Content-Disposition: inline`.
 *
 * Deliberately narrow. Anything the browser executes in this origin — HTML,
 * and SVG, which carries script — must stay an attachment, or an uploaded
 * file becomes stored XSS against the app's own origin. Raster images and
 * PDFs render in a viewer and cannot script the page.
 */
const INLINE_CONTENT_TYPES = new Set([
  "application/pdf",
  "image/png",
  "image/jpeg",
  "image/gif",
  "image/webp",
]);

/**
 * Durable, authenticated download for files in private storage buckets
 * (e.g. artifacts generated by sandbox code execution).
 *
 * This route is what gets persisted in a chat, so it must never expire; the
 * bytes themselves come from a short-lived signed URL the route redirects to.
 * Streaming the object through this function used to cap every download at
 * Vercel's 4.5 MB response limit — a generated Excel file above that size
 * simply failed. A driver without signed URLs still streams.
 *
 * GET /api/storage/download?key=<userId>/<uuid>-<filename>[&disposition=inline]
 *
 * `disposition=inline` exists for previewing: a browser will not render an
 * `attachment` response inside an iframe, so the PDF viewer pointed at the
 * default URL showed a blank frame (and never fired `onError`, so it sat on
 * its loading state forever). Attachment stays the default so every existing
 * download link keeps saving a file, with the clean filename (uuid stripped),
 * rather than navigating to one.
 */
export const GET = withAuth(async (req: Request, session) => {
  const url = new URL(req.url);
  const key = url.searchParams.get("key");
  if (!key || key.includes("..")) {
    return NextResponse.json(
      { error: "A valid storage key is required" },
      { status: 400 },
    );
  }

  // Keys are namespaced by owner; only the owner may download.
  if (!key.startsWith(`${session.user.id}/`)) {
    return NextResponse.json({ error: "Forbidden" }, { status: 403 });
  }

  const filename = downloadFilenameFromKey(key);
  const contentType = getContentTypeFromFilename(filename);
  const inline =
    url.searchParams.get("disposition") === "inline" &&
    INLINE_CONTENT_TYPES.has(contentType);

  try {
    // A driver without signed URLs streams the object through the function
    // (and inherits the platform's response-size cap).
    if (!serverFileStorage.getSignedUrl) {
      return await streamObject(key, filename, contentType, inline);
    }

    if (!(await serverFileStorage.exists(key))) {
      return NextResponse.json({ error: "File not found" }, { status: 404 });
    }

    const signedUrl = await serverFileStorage.getSignedUrl(
      key,
      SIGNED_URL_TTL_SECONDS,
      inline ? undefined : { download: filename },
    );
    if (!signedUrl) {
      logger.error(`[storage] signed url failed key=${key}`);
      return NextResponse.json({ error: "Download failed" }, { status: 500 });
    }

    return NextResponse.redirect(signedUrl, {
      status: 302,
      // The Location carries a token: never let a shared cache hand it out.
      headers: { "Cache-Control": "private, no-store" },
    });
  } catch (err) {
    if (err instanceof FileNotFoundError) {
      return NextResponse.json({ error: "File not found" }, { status: 404 });
    }
    logger.error(`[storage] download failed key=${key}`, err);
    return NextResponse.json({ error: "Download failed" }, { status: 500 });
  }
});

async function streamObject(
  key: string,
  filename: string,
  contentType: string,
  inline: boolean,
): Promise<Response> {
  const buffer = await serverFileStorage.download(key);
  return new Response(new Uint8Array(buffer), {
    headers: {
      "Content-Type": contentType,
      "Content-Disposition": `${inline ? "inline" : "attachment"}; filename="${filename.replaceAll('"', "")}"`,
      "Content-Length": String(buffer.byteLength),
      // The disposition decision above trusts the extension-derived type, so
      // the browser must not be allowed to sniff its way to a different one.
      "X-Content-Type-Options": "nosniff",
    },
  });
}
